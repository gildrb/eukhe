// The palette indexes by discriminant: `ALL` lists the enum in
// declaration order.
const _: () = {
    let mut index = 0;
    while index < Token::ALL.len() {
        assert!(Token::ALL[index] as usize == index);
        index += 1;
    }
};

#[cfg(test)]
mod tests {
    use super::Token;

    #[test]
    fn from_name_covers_all_tokens_and_is_case_sensitive() {
        for token in Token::ALL {
            assert_eq!(Token::from_name(token.name()), Some(token));
        }
        assert_eq!(Token::from_name("notAToken"), None);
        assert_eq!(Token::from_name("Accent"), None);
    }
}
