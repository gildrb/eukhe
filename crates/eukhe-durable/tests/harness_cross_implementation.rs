//! Cross-implementation check of the Harness against the TS package (no TS
//! test file): a process dies while a tool call runs, and the other
//! implementation picks the conversation up from the JSONL storage it left.
//!
//! Both sides run the same scenario: a Harness over JSONL storage with the
//! clock fixed at [`NOW`], a faux provider (`api: "faux"`, one chunk per
//! block) answering "Probe the disk." with the `probe` tool call `call-1`;
//! `probe` (replay `unsafe`, the default) reports output, a diagnostic, and
//! details, then the process exits once the details are durable. The resume
//! answers with a final text, waits for idle, and dumps the state.
//! The TS side ran the same steps as [`open`], [`crash`], [`resume`], and
//! [`dump_storage`] here, spelled with the TS API (`openNodeJsonlStorage`,
//! `fauxProvider`, `defineTool`, `Harness.open(storage, { models, registry,
//! now })`).
//!
//! `fixtures/harness_cross` (written by `@earendil-works/pi-durable` 1.1,
//! `main` at `42a3497d0`, and this crate):
//! - `ts-crash/`: the JSONL storage the TS process left (`process.exit(0)` in
//!   `execute`).
//! - `ts-crash-resumed.json` / `ts-crash-resumed/`: the final state and the
//!   JSONL files after TS resumed a copy of `ts-crash/`.
//! - `rust-crash/`: the JSONL storage a child process of this test left
//!   (`std::process::exit(0)` in `execute`), regenerated by the ignored
//!   `regenerate_rust_crash_fixture`.
//! - `rust-crash-resumed.json` / `rust-crash-resumed/`: the final state and
//!   the JSONL files after TS resumed a copy of `rust-crash/`.
//!
//! The final state is `{ toolRuns, context, storage }`: how often `probe` ran
//! during the resume (TS does not rerun an `unsafe` call: 0), the root's
//! `context()` view (`entries`, `contributions`, `messages`), and every record
//! the Storage API returns after close: conversations, each conversation's
//! entries oldest first, tasks, submissions, and every document alive at
//! `current` in the session, conversation, and task scopes, materialized.
//! States compare as `JSON.stringify` text (key order included); JSONL files
//! compare byte for byte. The only normalization is the `pi.provider`
//! document's `sessionId`, a random `UUIDv7` minted at conversation creation,
//! when a fresh crash run is compared with a fixture.
//!
//! The faux messages carry no `responseId`: TS `fauxAssistantMessage()`
//! writes it after `stopReason`, while `AssistantMessage` serializes in the
//! TS interface order (after `model`), so the stored message's key order
//! would differ for a reason outside the Harness.

