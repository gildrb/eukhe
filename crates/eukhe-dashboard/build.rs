//! Embeds the web app: every file under `web/` (dotfiles excepted) becomes
//! one entry of the generated asset table, with its content type, its
//! entity tag, and its bytes (`include_bytes!`). The web side stays
//! build-free: a new file under `web/` is served after the next cargo
//! build, with no table to edit. Also computes the digest of the whole
//! tree, which `hello` reports in its `build` value.
//!
//! A file whose extension has no known content type fails the build: the
//! server never guesses a type for what it ships.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// FNV-1a 64-bit offset basis and prime: a small, stable content hash
/// (no dependency, the same value on every platform and compiler).
const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
const FNV_PRIME: u64 = 0x0100_0000_01b3;

fn main() {
    let manifest_dir = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"),
    );
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let web = manifest_dir.join("web");
    // A directory is watched recursively: any added, removed or changed
    // file reruns this script.
    println!("cargo:rerun-if-changed=web");

    let mut files = Vec::new();
    collect(&web, &mut files);
    files.sort();

    let mut table = String::from(
        "/// Every file under `web/`, sorted by path (generated by `build.rs`).\n\
         pub(crate) const FILES: &[Asset] = &[\n",
    );
    let mut digest = FNV_OFFSET;
    for path in &files {
        let relative = path
            .strip_prefix(&web)
            .expect("collected under web/")
            .to_str()
            .unwrap_or_else(|| panic!("{}: the web file name is not UTF-8", path.display()))
            .replace('\\', "/");
        let bytes =
            std::fs::read(path).unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
        // The `Content-Type`, by extension.
        let extension = path
            .extension()
            .and_then(std::ffi::OsStr::to_str)
            .unwrap_or_default();
        let content_type = match extension {
            "html" => "text/html; charset=utf-8",
            "css" => "text/css; charset=utf-8",
            "js" | "mjs" => "text/javascript; charset=utf-8",
            "json" => "application/json",
            "webmanifest" => "application/manifest+json",
            "svg" => "image/svg+xml",
            "png" => "image/png",
            "ico" => "image/x-icon",
            "woff2" => "font/woff2",
            "txt" => "text/plain; charset=utf-8",
            other => panic!(
                "{}: no content type for {other:?} files; add one to crates/eukhe-dashboard/build.rs",
                path.display()
            ),
        };
        let hash = fnv(fnv(FNV_OFFSET, relative.as_bytes()), &bytes);
        digest = fnv(digest, relative.as_bytes());
        digest = fnv(digest, &hash.to_le_bytes());
        let absolute = path
            .to_str()
            .unwrap_or_else(|| panic!("{}: the web path is not UTF-8", path.display()));
        writeln!(
            table,
            "    Asset {{ path: {relative:?}, content_type: {content_type:?}, etag: \"\\\"{hash:016x}\\\"\", body: include_bytes!({absolute:?}) }},"
        )
        .expect("write to a String");
    }
    table.push_str("];\n\n");
    writeln!(
        table,
        "/// The digest of every file under `web/`: changes whenever any of\n\
         /// them does.\n\
         pub(crate) const DIGEST: &str = \"{digest:016x}\";"
    )
    .expect("write to a String");
    std::fs::write(out_dir.join("web_assets.rs"), table).expect("write the asset table");
}

/// Every regular file under `dir`, recursively; dotfiles and dot-folders
/// (editor and OS litter) are skipped.
fn collect(dir: &Path, files: &mut Vec<PathBuf>) {
    let entries =
        std::fs::read_dir(dir).unwrap_or_else(|error| panic!("read {}: {error}", dir.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("read {}: {error}", dir.display()));
        if entry.file_name().to_string_lossy().starts_with('.') {
            continue;
        }
        let path = entry.path();
        let kind = entry
            .file_type()
            .unwrap_or_else(|error| panic!("stat {}: {error}", path.display()));
        if kind.is_dir() {
            collect(&path, files);
        } else {
            files.push(path);
        }
    }
}

/// FNV-1a over `bytes`, continuing from `hash`.
fn fnv(hash: u64, bytes: &[u8]) -> u64 {
    bytes.iter().fold(hash, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(FNV_PRIME)
    })
}
